// QA sheet: all 21 in a grid as one SVG
const slugs = Object.keys(MOBS);
const cols = 7, S = 16;
const parts = slugs.map((slug, i) => {
  const ox = (i % cols) * (S + 2) * 8, oy = Math.floor(i / cols) * (S + 2) * 8;
  return `<g transform="translate(${ox},${oy}) scale(8)">${svg(MOBS[slug].rows, MOBS[slug].pal).replace(/<svg[^>]*>/,'').replace('</svg>','')}</g>`;
});
fs.writeFileSync('/tmp/mob-sheet.svg', `<svg xmlns="http://www.w3.org/2000/svg" width="${cols*18*8}" height="${Math.ceil(slugs.length/cols)*18*8}" shape-rendering="crispEdges" style="background:#14181f">${parts.join('')}</svg>`);
