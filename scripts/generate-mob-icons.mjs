import fs from 'node:fs';

function svg(rows, pal) {
  const rects = [];
  rows.forEach((row, y) => { [...row].forEach((ch, x) => { if (pal[ch]) rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${pal[ch]}"/>`); }); });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects.join('')}</svg>`;
}

